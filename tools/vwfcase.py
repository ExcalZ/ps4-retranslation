"""True capitals and true lowercase to accompany the small-caps face.

`vwffont` is a single small-caps alphabet on rows 3-7. That is right for
technique and item names, where every letter is the same height, but it gives
no case distinction at all: "Gifeuer" reads as GIFEUER, and party names come
out as RUDY rather than Rudy.

Two more sets, sharing the same baseline (row 7):

    CAPS   rows 2-7, six rows      one row taller than a small cap and one or
                                   two pixels wider - enough to read as a
                                   capital beside small caps, without the jump
                                   in size the stock 8x8 uppercase would give
    LOW    x-height rows 4-7,      NO DESCENDERS: the cell ends at row 7, and
           ascenders from row 2    dropping the baseline to make room would
                                   misalign every glyph against unconverted
                                   text. g j p q y sit on the baseline.

`lowerfont` reached the same conclusion about descenders for the fixed-pitch
bank, for the same reason.

Both sets cost nothing in table size: the font entry already carried two bytes
of padding, so it becomes [width, seven rows] and a glyph simply starts higher
up the cell.
"""

CAPS = {}
LOW = {}


def _c(ch, *rows):
    CAPS[ch] = (2, tuple(rows))


def _l(ch, top, *rows):
    LOW[ch] = (top, tuple(rows))



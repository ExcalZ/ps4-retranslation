def bitmap(ch):
    """16x16 bitmap with the glyph in the left half, or None if unknown."""
    if ch not in G:
        return None
    top, rows = G[ch]
    p = [[0] * CELL_W for _ in range(CELL_H)]
    for dy, row in enumerate(rows):
        y = top + dy
        if not 0 <= y < CELL_H:
            raise ValueError(f'{ch!r} row {y} outside the cell')
        for dx, c in enumerate(row):
            if c == '#':
                p[y][X + dx] = 1
    return p


def glyph_bytes(ch):
    """32 bytes in the game's four-8x8-tiles row-major layout."""
    import font
    return font._bitmap_to_glyph(bitmap(ch))


def available():
    return ''.join(sorted(G))

"""The menu VWF face: a proportional mixed-case alphabet on the stock 8x8
font's own vertical metrics.

This replaces the small caps (`vwffont.G`) and the true capitals that sat
over them (`vwfcase.CAPS`) as the face `menuvwf.py` emits.  What decided it,
measured over every name table and set into saved screens (2026-09-14):

    x-height     5 rows (2-6).  The 4-row lowercase in `vwfcase.LOW` is
                 cramped at 8 px; five rows is what makes e/a/s read.
    descender    1 row (7) on g j p q y - shallow, but present.
    capitals     7 rows (0-6), 4 px wide (M N V W X Y are 5).  A 4 px cap
                 next to a 4 px lowercase is where the width comes from:
                 caps average 5.1 px advance against 6.1 before.
    baseline     row 6 - the row the stock 8x8 letters sit on, so composed
                 text is level with the fixed HP/TP/LV labels drawn from
                 $7C0 and with stock lowercase in battle messages, and one
                 row above the digits exactly as stock is.  The old face
                 bottomed on row 7 and sat a row low beside all of them.

Widths, over the tables as translated: lowercase 4.65 px mean advance
(4.51 weighted by use) against the small caps' 5.08; items average 51 px
against 56, widest 9 cells against 10.  Nothing crosses a stock budget.

Every glyph is (top_row, rows): rows are strings of '#'/'.' drawn from cell
row `top_row` down, and the advance is the ink width plus the composer's
1 px gap.  Digits and marks are drawn to cap height on the same baseline.
Ink stays inside rows 0-7 and 8 columns - the composer writes one tile row.
"""

G = {}


def _g(ch, top, *rows):
    w = max(len(r) for r in rows)
    if top + len(rows) > 8 or w > 8:
        raise ValueError('%r does not fit an 8x8 cell' % ch)
    G[ch] = (top, tuple(r.ljust(w, '.') for r in rows))


